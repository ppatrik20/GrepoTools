/**
 * Simulates the 5% hourly attrition curve of the Olympus Curse (Olimposz átka).
 * Formula per tick: U(t) = U_0 * (0.95)^t
 */
export function simulateOlympusCurseAttrition(initialTroops, intervals = 24) {
  const curve = [];
  let current = Number(initialTroops) || 0;

  for (let i = 0; i <= intervals; i++) {
    const remaining = Math.round(Number(initialTroops) * Math.pow(0.95, i));
    curve.push({
      interval: i,
      remainingTroops: remaining,
      totalLostToCurse: (Number(initialTroops) || 0) - remaining,
      lossThisInterval: i === 0 ? 0 : curve[i - 1].remainingTroops - remaining
    });
  }

  return curve;
}

/**
 * Calculates outbound two-leg transit times via a Portal Temple versus direct Euclidean route,
 * and highlights the official Grepolis rule that return transit from Olympus CANNOT use the portal.
 */
export function calculatePortalRouteTiming({
  originToPortalSeconds = 0,
  portalTeleportSeconds = 0,
  directOriginToOlympusSeconds = 0,
  hasAresLargeTemple = false
}) {
  const speedMult = hasAresLargeTemple ? 1.15 : 1.0;

  const adjustedOriginToPortal = Math.round(Number(originToPortalSeconds) / speedMult);
  const adjustedDirect = Math.round(Number(directOriginToOlympusSeconds) / speedMult);

  // Portal teleport duration is fixed server hours (not affected by unit movement speed)
  const outboundViaPortalSeconds = adjustedOriginToPortal + Number(portalTeleportSeconds);
  const returnDirectSeconds = adjustedDirect; // Returning troops walk the long direct way home!

  const isPortalFaster = outboundViaPortalSeconds < adjustedDirect;
  const timeSavedSeconds = Math.max(0, adjustedDirect - outboundViaPortalSeconds);

  return {
    outboundViaPortalSeconds,
    returnDirectSeconds,
    isPortalFaster,
    timeSavedSeconds,
    aresSpeedBonusApplied: hasAresLargeTemple
  };
}

/**
 * Generates a staggered reinforcement relay schedule across team members to replace
 * the 5% Olympus Curse attrition without dumping all defense into the curse early.
 */
export function generateReinforcementRelaySchedule({
  shieldEndsAt,
  teamMembers = [],
  shiftIntervalHours = 6,
  shiftCount = 4
}) {
  const shiftNames = ['Shift Alpha', 'Shift Bravo', 'Shift Charlie', 'Shift Delta', 'Shift Echo', 'Shift Foxtrot'];
  const startEpoch = new Date(shieldEndsAt).getTime();
  const schedule = [];

  for (let s = 0; s < shiftCount; s++) {
    const arrivalTime = new Date(startEpoch + s * shiftIntervalHours * 3600 * 1000);
    const assignedMember = teamMembers[s % teamMembers.length] || null;

    schedule.push({
      shiftIndex: s,
      shiftName: shiftNames[s % shiftNames.length],
      targetArrival: arrivalTime,
      assignedMember,
      shiftIntervalHours
    });
  }

  return schedule;
}

