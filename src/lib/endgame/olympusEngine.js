export function calculateCurseAttritionCurve({ initialTroops = 10000, days = 14 }) {
  const curve = simulateOlympusCurseAttrition(initialTroops, days);
  return curve.map(c => ({
    day: c.interval,
    troopsRemaining: c.remainingTroops,
    troopsLostTotal: c.totalLostToCurse,
    troopsLostStep: c.lossThisInterval
  }));
}
